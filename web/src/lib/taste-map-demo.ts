// Curated examples for the public preview. These IDs never identify a playable catalog item.
function demoTrack(
  catalogId: number, name: string, artists: string[], album: string, duration: number,
  cover: string, centerIds: string[], reason: string,
): TasteTrack {
  return {
    song: {
      id: `demo:${catalogId}`, name, duration, cover,
      album: { id: null, name: album },
      artists: artists.map(artist => ({ id: `demo:${artist}`, name: artist })),
    },
    centerIds, reason,
  };
}

// The example listener has played every fifth track. Live accounts use their stored history.
function sampleLibrary(input: TasteTrack[]) {
  const tracks = input.map((track, index) => ({ ...track, unheard: index % 5 !== 0 }));
  return { tracks, mixIds: tracks.filter(track => track.unheard).slice(0, 36).map(track => track.song.id) };
}

